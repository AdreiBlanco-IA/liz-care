const dicts: Record<Lang, Record<Key, string>> = { es, en }

interface I18n { lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string }
const Ctx = createContext<I18n | null>(null)
const KEY = 'lizcare.lang'

function inicial(): Lang {
  try {
    const v = localStorage.getItem(KEY)
    if (v === 'es' || v === 'en') return v
  } catch { /* sin almacenamiento */ }
  return 'es'
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(inicial)
  const setLang = (l: Lang) => {
    setLangState(l)
    try { localStorage.setItem(KEY, l) } catch { /* sin almacenamiento */ }
  }
  const t = (k: Key) => dicts[lang][k]
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export function useI18n() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n debe usarse dentro de LangProvider')
  return ctx
}
